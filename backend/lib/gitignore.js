"use strict";

const fs = require("fs");
const path = require("path");

const LATCH_GITIGNORE_ENTRIES = [
  ".latch/",
  ".relay/",
  ".cursor/",
  ".claude/",
  ".codex/",
  ".agents/",
  ".cursorrules",
  "AGENTS.md",
  "CLAUDE.md",
  "**/copilot-instructions.md",
  ".github/hooks/",
  ".github/mcp.json",
];

function normalize(str) {
  return str.trim().replace(/^\.?\/+/, "").replace(/\/+$/, "");
}

function isPatternCovered(entry, existingLines) {
  const normEntry = normalize(entry);
  return existingLines.some((rawLine) => {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) return false;
    const normLine = normalize(line);

    // Exact match
    if (normLine === normEntry) return true;

    // Directory match (e.g. .cursor/ covers .cursor/hooks.json or .cursor/)
    if (
      (normLine === ".cursor" && normEntry.startsWith(".cursor")) ||
      (normLine === ".claude" && normEntry.startsWith(".claude")) ||
      (normLine === ".codex" && normEntry.startsWith(".codex")) ||
      (normLine === ".agents" && normEntry.startsWith(".agents")) ||
      (normLine === ".latch" && normEntry.startsWith(".latch")) ||
      (normLine === ".relay" && normEntry.startsWith(".relay")) ||
      (normLine === ".github/hooks" && normEntry.startsWith(".github/hooks"))
    ) {
      return true;
    }

    // Copilot instructions matching
    if (
      (line === "**/copilot-instructions.md" || normLine === ".github/copilot-instructions.md" || normLine === "copilot-instructions.md") &&
      (entry === "**/copilot-instructions.md" || normEntry.endsWith("copilot-instructions.md"))
    ) {
      return true;
    }

    return false;
  });
}

function updateGitignore(workspacePath) {
  if (!workspacePath) return { ok: false, error: "workspace_required" };
  const targetDir = path.resolve(workspacePath);
  const gitignorePath = path.join(targetDir, ".gitignore");

  let existingContent = "";
  if (fs.existsSync(gitignorePath)) {
    try {
      existingContent = fs.readFileSync(gitignorePath, "utf8");
    } catch (err) {
      return { ok: false, error: err.message };
    }
  }

  const existingLines = existingContent.split(/\r?\n/);
  const missing = LATCH_GITIGNORE_ENTRIES.filter((entry) => !isPatternCovered(entry, existingLines));

  if (missing.length === 0) {
    return { ok: true, added: [], gitignorePath };
  }

  let newContent = existingContent;
  if (newContent.length > 0 && !newContent.endsWith("\n")) {
    newContent += "\n";
  }

  // Check if latch comment already exists
  const hasLatchComment = existingLines.some((l) => l.trim().toLowerCase().includes("latch"));
  if (!hasLatchComment) {
    newContent += "\n# Agent / IDE config (machine-generated by latch, cursor, copilot, codex, etc.)\n";
  }

  newContent += missing.join("\n") + "\n";

  try {
    fs.writeFileSync(gitignorePath, newContent, "utf8");
    return { ok: true, added: missing, gitignorePath };
  } catch (err) {
    return { ok: false, error: err.message };
  }
}

module.exports = {
  updateGitignore,
  LATCH_GITIGNORE_ENTRIES,
  isPatternCovered,
};
